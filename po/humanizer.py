"""Humanizer для ставок: правила для модели и проверка результата без модели."""
import re

RULES = """Ты редактор. Убираешь из текста ставки признаки, по которым видно, что его написала нейросеть.
Смысл, факты, цифры, названия и ссылки не меняешь. Ничего не добавляешь от себя. Язык текста сохраняешь.

Что убрать или переписать:
1. Длинные и средние тире (— и –). В тексте их быть не должно. Замени точкой, запятой, двоеточием или перестрой фразу.
2. Шаблонные открытия: «Здравствуйте! Меня заинтересовал ваш проект», «Внимательно ознакомился с ТЗ», «Готов взяться за ваш проект», «Добрый день! С радостью помогу». Начинай сразу с сути.
3. Шаблонные концовки: «Буду рад сотрудничеству», «Жду вашего ответа», «Обращайтесь», «С уважением», «Готов обсудить детали в личных сообщениях».
4. Пустые слова и канцелярит: ключевой, уникальный, комплексный, эффективный, индивидуальный подход, качественно и в срок, профессионально, гарантирую, большой опыт, является, данный, осуществить, обеспечить, позволит, в рамках, на высоком уровне, под ключ (если не по делу).
5. Конструкции «не просто X, а Y», «это не только X, но и Y».
6. Перечисления ровно из трёх пунктов ради ритма, списки, нумерация, жирный шрифт, markdown, эмодзи.
7. Угодливость и восклицательные знаки. Лишние оговорки («возможно, могу попробовать»).
8. Все предложения одной длины. Пусть одно будет короче, другое длиннее, как пишет живой человек в переписке.

Как должно звучать: коротко, по-деловому, от первого лица, как сообщение заказчику в чате. Без воды.
Абзацы и пустые строки между ними сохраняй. Обращение по имени и вопрос в конце оставляй.
Верни только исправленный текст ставки."""

_TELLS = [
    (r"[—–]", "длинное тире"),
    (r"\*\*|__|^#|^\s*[-•*]\s", "markdown или список"),
    (r"[\U0001F300-\U0001FAFF☀-➿]", "эмодзи"),
    (r"меня заинтересовал|внимательно (ознакомил|изучил|прочитал)|готов взяться", "шаблонное начало"),
    (r"буду рад|жду (вашего )?ответа|с уважением|обращайтесь|рад(а)? буду", "шаблонная концовка"),
    (r"индивидуальн\w+ подход|качественно и в срок|на высоком уровне|комплексн\w+ решени|гарантирую", "канцелярит"),
    (r"не просто [^.,]+, а |не только [^.,]+, но и ", "не просто X, а Y"),
    (r"!", "восклицательный знак"),
]


def find_tells(text: str) -> list[str]:
    found = []
    for pattern, name in _TELLS:
        if re.search(pattern, text, re.I | re.M):
            found.append(name)
    return found


def cleanup(text: str) -> str:
    """Механическая страховка после модели: тире, markdown, эмодзи, пробелы."""
    t = text.replace("\r", "")
    t = re.sub(r"\s*\(?\[[rp]\d+\]\)?", "", t)
    t = re.sub(r"(\d)\s*[—–]\s*(\d)", r"\1-\2", t)
    t = re.sub(r"\s*[—–]\s*", ", ", t)
    t = re.sub(r",\s*([.,:;!?])", r"\1", t)
    t = re.sub(r"\*\*|__", "", t)
    t = re.sub(r"[\U0001F300-\U0001FAFF☀-➿]️?", "", t)
    t = t.replace("!", ".")
    t = re.sub(r"\.{2,}", ".", t)
    t = re.sub(r"[ \t]+", " ", t)
    t = re.sub(r" +([.,:;?])", r"\1", t)
    t = re.sub(r"\n{3,}", "\n\n", t)
    return "\n".join(line.strip() for line in t.split("\n")).strip()
