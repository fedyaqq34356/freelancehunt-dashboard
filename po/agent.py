PLAN_VERBS = re.compile(
    r"\b(сделаю|проверю|подключу|настрою|добавлю|реализую|разработаю|сверю|посмотрю|напишу|интегрирую|доработаю|"
    r"создам|соберу|внедрю|проанализирую|изучу|перепишу|оптимизирую|разберусь|перевірю|зроблю|додам|налаштую|підключу)\b",
    re.I,
)
GENERIC = re.compile(
    r"(есть|имею|маю)\s+(\w+\s+)?(опыт|досвід)|у меня есть (\w+\s+){0,2}(работ|проект|доработк)|делал похож|робив схож|каталог"
    r"|среди (моих )?работ нет|готово\w* .{0,30}нет",
    re.I,
)
HOURLY = re.compile(r"\$\s?\d+\s?/\s?ч|ставк\w* \$|\d+\s?(грн|uah|usd|eur|\$)?\s?(/|в)\s?(ч\b|час)", re.I)
REF = re.compile(r"[rp]\d+")
MAX_LEN = 700

BID_RULES = """Ты По. Пишешь ставку на Freelancehunt от первого лица фрилансера. Он делает на Python Telegram-ботов, парсеры, AI-агентов и автоматизацию, сайты, CRM, админки и дашборды.
Цель ставки одна: чтобы заказчик ответил. Не продать всё сразу, а получить ответ.

Как заказчик читает ставки. У него 10-30 откликов. Он пробегает первые две строки и решает за несколько секунд, в превью видно около 150 знаков. Почти все отклики одинаковые: «Здравствуйте, готов выполнить», «Есть опыт», «Сделаю качественно». Твоя ставка с первой строки показывает, что ты понял именно его задачу и уже делал такое.

Психология, на которой строится ставка:
1. Человека тянет к тому, кто понял его без объяснений. Первая фраза называет суть его задачи его же словами и сразу связывает её с твоей готовой работой. Если известно имя заказчика, начни с имени.
2. Конкретика убеждает, общие слова нет. Одна готовая система и что она делает (только из каталога) сильнее любого списка навыков.
3. Чужое мнение весит больше своего. Если есть похожий проект с отзывом, сошлись на него одной живой фразой (что сказал заказчик), а не «есть положительный отзыв». Факт из профиля бери, только если он про эту же категорию и сильный (например, 3 место в рейтинге AI для AI-проекта). Общую статистику (число проектов, отзывов) не перечисляй.
4. Экспертность видно по замечанию, до которого заказчик сам не додумался. Добавь одну короткую мысль про подводный камень или важную деталь его задачи. Это общее знание предметной области, а не выдуманный опыт. Это маленький подарок, а тому, кто уже дал пользу, хочется ответить.
5. Страх ошибиться сильнее желания выиграть. Сними риск: готовая основа значит быстрее и предсказуемее. Можно предложить начать с первого этапа или показать похожую систему в работе.
6. На лёгкий вопрос отвечают, на сложный нет. Закончи одним вопросом, на который можно ответить за 5 секунд: выбор из двух вариантов или да/нет по ключевой детали задачи. Не «есть вопросы?», а конкретно про его задачу.
7. Уверенность без давления. Без заискивания, без «надеюсь», «если вам интересно», «буду рад», без восклицаний. Пишешь как спокойный специалист, для которого такая задача привычна.

Форма:
- 3 коротких абзаца через пустую строку. Первый: его задача и твоя готовая система. Второй: доказательство и одна экспертная мысль. Третий: цена, срок, почему так, и вопрос.
- 350-650 знаков. Язык проекта (русский или украинский), на «вы».
- Не расписывай план работ по шагам. Что уже есть, говори как факт. Чего не хватает, называй одной фразой.
- Готовую систему описывай только тем, что про неё написано в каталоге. Детали задачи заказчика готовой системе не приписывай.
- Никаких выдуманных цифр, клиентов и технологий. Только каталог и факты профиля. Почасовую ставку не называй. Условия и цифры из текста заказчика не выдавай за свои.
- Глаголы будущего времени про свою работу («проверю», «подключу», «сделаю», «посмотрю») можно использовать максимум один раз на всю ставку. Остальное: что уже есть и работает.
- Не пиши «у меня есть опыт», «имею опыт», «делал похожее». Вместо этого назови конкретную готовую систему.
- Ref кейсов ([r...], [p...]) в текст ставки не вставляй, они только для поля cases. Слово «каталог» не используй: заказчик его не видит.
- Если похожего мало (fit=low или medium), не делай вид, что всё готово, но и не пиши, чего у тебя нет. Начни с точного понимания его задачи и экспертной мысли, а ближайшую готовую систему упомяни как доказательство.
- Без шаблонных приветствий, markdown, списков, эмодзи и длинных тире.

Два образца тона и структуры. Факты в них вымышлены, в своей ставке бери факты только из каталога.

Образец 1:
Анна, запись к мастеру с предоплатой у меня уже работает в другом боте: клиент выбирает услугу и время, платит картой, мастеру приходит уведомление.

Заказчик того бота написал, что всё сделано быстро и с учётом пожеланий. Один момент, который часто упускают: если клиент не оплатил за 15 минут, слот должен освобождаться сам, иначе расписание забивается висящими записями.

Основа готова, поэтому 5 000 грн вместо 6 000 и 4 дня. Мастер у вас один или несколько?

Образец 2:
Сравнение цен конкурентов на Rozetka и Prom у меня собирается из двух рабочих парсеров: один по расписанию выгружает товары Rozetka в Google Sheets, второй забирает каталог Prom.ua.

Для 300 позиций важно сопоставлять товары по артикулу или штрихкоду, а не по названию, иначе часть цен попадёт не в ту строку.

5 дней, 3 500 грн, первые 20 товаров будут в таблице уже на второй день. Ссылки на товары конкурентов у вас есть или их тоже нужно найти?

Как выбирать кейсы: по сути задачи, а не по словам (что система делает, с какими данными и сервисами работает). Кейсы с отзывом ([r...]) ценнее при равной похожести. 1-3 кейса, только ref из каталога.

Цена в валюте проекта. Если есть готовая основа и бюджет указан, ставь немного ниже бюджета, примерно 80-95%, и объясни это готовой основой. Ниже 70% бюджета не опускайся. Без бюджета ориентируйся на бюджеты похожих кейсов. Срок реалистичный.
note: подсказка фрилансеру, не заказчику. Риск, что уточнить, стоит ли браться."""

BID_SCHEMA = {
    "type": "object",
    "additionalProperties": False,
    "properties": {
        "fit": {"type": "string", "enum": ["high", "medium", "low"]},
        "cases": {
            "type": "array",
            "items": {
                "type": "object",
                "additionalProperties": False,
                "properties": {"ref": {"type": "string"}, "why": {"type": "string"}},
                "required": ["ref", "why"],
            },
        },
        "bid": {"type": "string"},
        "price": {"type": ["integer", "null"]},
        "days": {"type": ["integer", "null"]},
        "note": {"type": "string"},
    },
    "required": ["fit", "cases", "bid", "price", "days", "note"],
}

HUMAN_SCHEMA = {
    "type": "object",
    "additionalProperties": False,
    "properties": {"bid": {"type": "string"}},
    "required": ["bid"],
}

MAX_CASES_IN_PROMPT = 120


@dataclass
class Pick:
    case: Case
    why: str


@dataclass
class BidDraft:
    text: str
    fit: str
    picks: list[Pick] = field(default_factory=list)
    price: Optional[int] = None
    days: Optional[int] = None
    currency: str = ""
    note: str = ""


def render_project(p: Project) -> str:
    return "\n".join(
        [
            f"Название: {p.name}",
            f"Заказчик: {p.employer_name or 'имя неизвестно'}",
            f"Бюджет: {p.budget}",
            f"Навыки: {', '.join(p.skills) or 'не указаны'}",
            f"Ставок уже: {p.bid_count}",
            "Описание:",
            clip(p.description, 3500) or "(пусто)",
        ]
    )


def review_bid(text: str) -> list[str]:
    """Проверка ставки без модели: план работ, общие слова, длина."""
    issues = []
    plan = PLAN_VERBS.findall(text)
    if len(plan) > 1:
        issues.append(f"слишком много обещаний сделать ({', '.join(plan)}), оставь максимум одно, остальное перепиши через то, что уже готово")
    if GENERIC.search(text):
        issues.append("общая фраза про опыт или слово «каталог», замени конкретной готовой системой")
    if HOURLY.search(text):
        issues.append("почасовая ставка, убери её, называй только цену за работу")
    if len(text) > MAX_LEN:
        issues.append(f"слишком длинно ({len(text)} знаков), нужно до 650")
    if re.search(r"\[[rp]\d+\]", text):
        issues.append("в тексте служебные ref, убери их")
    return issues


class Po:
    def __init__(self, llm: LLM):
        self.llm = llm

    async def write_bid(
        self, project: Project, cases: list[Case], facts: str = "", previous: Optional[str] = None
    ) -> BidDraft:
        catalog = cases[:MAX_CASES_IN_PROMPT]
        prompt = f"ПРОЕКТ\n{render_project(project)}\n\nКАТАЛОГ МОИХ РАБОТ\n{render_for_prompt(catalog)}"
        if facts:
            prompt += f"\n\nФАКТЫ ПРОФИЛЯ\n{facts}"
        if previous:
            prompt += f"\n\nПРЕДЫДУЩИЙ ВАРИАНТ (не повторяй его, напиши по-другому, можно с другими кейсами):\n{previous}"
        raw = await self.llm.json(instructions=BID_RULES, prompt=prompt, schema=BID_SCHEMA, name="bid", effort="medium")
        first = raw
        for _ in range(2):
            issues = review_bid(raw.get("bid", ""))
            if not issues:
                break
            fix = f"{prompt}\n\nТВОЙ ЧЕРНОВИК\n{raw.get('bid', '')}\n\nПерепиши ставку. Проблемы: {'; '.join(issues)}."
            raw = await self.llm.json(instructions=BID_RULES, prompt=fix, schema=BID_SCHEMA, name="bid", effort="medium")
        if not raw.get("cases"):
            raw["cases"] = first.get("cases") or []

        by_ref = {c.ref: c for c in catalog}
        picks = []
        for item in raw.get("cases") or []:
            m = REF.search(str(item.get("ref", "")))
            case = by_ref.get(m.group(0)) if m else None
            if case and all(p.case.ref != case.ref for p in picks):
                picks.append(Pick(case, item.get("why", "")))
        text = await self.humanize(raw.get("bid", ""))
        return BidDraft(
            text=text,
            fit=raw.get("fit", "medium"),
            picks=picks[:3],
            price=raw.get("price"),
            days=raw.get("days"),
            currency=project.currency or "UAH",
            note=raw.get("note", ""),
        )

    async def humanize(self, text: str) -> str:
        """Humanizer: правка моделью, повтор с подсказкой, если признаки остались, и механическая чистка."""
        prompt = text
        for _ in range(2):
            out = await self.llm.json(
                instructions=humanizer.RULES, prompt=prompt, schema=HUMAN_SCHEMA, name="humanize", effort="none", max_tokens=800
            )
            text = out.get("bid") or text
            tells = humanizer.find_tells(text)
            if not tells:
                break
            prompt = f"{text}\n\nВ тексте остались признаки: {', '.join(tells)}. Исправь их."
        return humanizer.cleanup(text)
